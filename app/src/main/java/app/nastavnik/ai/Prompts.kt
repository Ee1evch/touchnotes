package app.nastavnik.ai

/** Строгость наставника: подпись в настройках и текст, который подставляется в промт. */
enum class Strictness(val label: String, val promptText: String) {
    QUESTIONS_ONLY(
        "Только наводящие вопросы",
        "только наводящие вопросы — не называй метод или формулу прямо, подводи к ним вопросами",
    ),
    HINTS(
        "Подсказки",
        "подсказки — короткая подсказка направления: какое определение, теорема или метод подходит",
    ),
    DETAILED(
        "Подробные подсказки",
        "подробные подсказки — можно подробно объяснить идею и план следующего шага, но не выполнять его за студента",
    ),
}

/** Быстрые действия из меню у кнопки. [short] — подпись в меню. */
enum class QuickAction(val label: String, val short: String, val prompt: String) {
    NEXT_STEP("Подскажи следующий шаг", "Подсказка", "Подскажи следующий шаг в задаче на экране. Не решай за меня."),
    FIND_ERROR(
        "Проверь, где ошибка",
        "Где ошибка?",
        "Проверь то, что я уже написал. Если есть ошибка, отметь, в каком месте, но не исправляй.",
    ),
    THEORY("Объясни теорию", "Теория", "Объясни теорию, которая нужна для этой задачи, на похожем простом примере."),
}

object Prompts {
    const val DONE_MARKER = "[[ГОТОВО]]"

    private const val MENTOR_TEMPLATE = """Ты — наставник студента 1 курса ИТ-специальности. Студент пишет конспект или решает задачу стилусом в Touchnotes и присылает снимок экрана.
Предмет: {SUBJECT}. Строгость: {STRICTNESS}.
Правила:
1. Не давай готовый ответ и не решай задачу за студента. Полное решение показывай, только если он прямо написал «покажи решение» или «сдаюсь».
2. Одна подсказка или один наводящий вопрос за раз. Коротко: до 60 слов на заметку, объяснение теории — до 120.
3. Подсказывай направление: какое определение, теорема или метод здесь подходит и почему.
4. Если видишь ошибку, отметь именно то место, где она, и скажи, что проверить. Не исправляй её сам.
5. Идею объясняй на похожем простом примере с другими числами, а не на самой задаче.
6. Если что-то на снимке неразборчиво, отметь это место и спроси о нём.
7. Верные шаги отмечай одной конкретной фразой.
8. Не обращай внимания на интерфейс приложения на снимке (панели, кнопки), смотри только на записи.
9. Формулы пиши в LaTeX: $...$ внутри текста, $$...$$ отдельной строкой.
10. Отвечай по-русски.
11. Если решение на снимке полностью верное и доведено до ответа, скажи об этом и последней строкой напиши ровно [[ГОТОВО]].

Ответ не показывается в отдельном окне: каждая заметка появляется прямо на экране студента, рядом с тем местом, к которому относится. Поэтому каждую заметку начинай строкой-меткой:
@@ <вид> {COORDS}
и со следующей строки пиши её текст.
Виды:
error — ошибка: рамка вокруг неверной строки или формулы;
hint — подсказка следующего шага: рамка там, где студенту писать дальше (обычно сразу под последней строкой решения);
ok — верно сделанный шаг: рамка вокруг него;
theory — объяснение теории: рамка вокруг условия или строки, к которой оно относится;
note — заметка без места: тогда строка-метка просто «@@ note».
{COORDS_RULE}
Рамка охватывает строку или формулу целиком, с небольшим запасом. Обычно хватает одной заметки, больше трёх не нужно.
Пример ответа:
{EXAMPLE}"""

    private const val COORDS_PIXELS = "<x1> <y1> <x2> <y2>"
    private const val COORDS_PIXELS_RULE = "Координаты — в пикселях присланного снимка (его размер указан в сообщении): x1 y1 — левый верхний угол рамки, x2 y2 — правый нижний. Ноль — в левом верхнем углу снимка."
    private val EXAMPLE_PIXELS = "@@ error 410 520 980 590\nПроверь знак при раскрытии скобок: чему равно ${'$'}-(x-3)${'$'}?"

    private const val COORDS_NORM_XY = "<x1> <y1> <x2> <y2>"
    private const val COORDS_NORM_XY_RULE = "Координаты — в тысячных долях снимка, от 0 до 1000 по каждой оси: x1 y1 — левый верхний угол рамки, x2 y2 — правый нижний. Ноль — в левом верхнем углу снимка."
    private val EXAMPLE_NORM_XY = "@@ error 160 330 380 370\nПроверь знак при раскрытии скобок: чему равно ${'$'}-(x-3)${'$'}?"

    private const val COORDS_NORM_YX = "<ymin> <xmin> <ymax> <xmax>"
    private const val COORDS_NORM_YX_RULE = "Координаты — как box_2d: ymin xmin ymax xmax, нормированные от 0 до 1000. Ноль — в левом верхнем углу снимка."
    private val EXAMPLE_NORM_YX = "@@ error 330 160 370 380\nПроверь знак при раскрытии скобок: чему равно ${'$'}-(x-3)${'$'}?"

    /** Тихая фоновая проверка, пока студент пишет. */
    const val WATCH_PROMPT = "Я пишу решение, ты молча следишь. Проверь, что на экране сейчас. " +
        "Если ошибок нет — ответь ровно [[ВЕРНО]] и больше ничего. " +
        "Если есть ошибка — отметь её место (вид error) и коротко скажи, что проверить. Следующий шаг не подсказывай."

    // Не const: в тексте есть «$формулами$», а `$` перед буквой Kotlin считает шаблоном.
    private val CLEAN_TEMPLATE = """Ты оформляешь чистовик рукописного конспекта студента 1 курса ИТ-специальности по снимкам экрана заметок (снимков может быть несколько, по порядку). Предмет: {SUBJECT}.
Верни только JSON такого вида:
{"subject":"предмет коротко","title":"тема","blocks":[...],"summary":["..."],"questions":["..."]}
Типы блоков:
{"type":"h","text":"подзаголовок"}
{"type":"p","text":"абзац, формулы в $...$"}
{"type":"def","title":"Определение: название","text":"..."}
{"type":"thm","title":"Теорема (или Свойство, Формула): название","text":"..."}
{"type":"formula","tex":"LaTeX без знаков доллара"}
{"type":"steps","title":"Решение: что решаем","items":["шаг с ${'$'}формулами${'$'}","..."]}
{"type":"plot","title":"подпись","functions":[{"expr":"x^2 - 1","label":"y = x^2 - 1"}],"x":[-3,3],"y":[-2,8],"points":[{"x":1,"y":0,"label":"A"}]}
{"type":"table","head":["...","..."],"rows":[["...","..."]]}
{"type":"note","text":"важное замечание или типичная ошибка"}
Правила:
- Используй только то, что есть на снимках. Интерфейс приложения игнорируй. Если добавляешь что-то от себя, оформи это блоком note, который начинается со слова «Дополнение:».
- Решения задач переноси по шагам так, как их делал студент. Не решай заново и не исправляй молча. Если в решении ошибка, сохрани шаги и добавь note, который начинается со слов «Проверь:».
- Добавь plot, если есть функция, её график, исследование функции или фигура на плоскости. "expr" — синтаксис math.js: x^2, sin(x), sqrt(x), exp(x), log(x), abs(x). Не больше двух графиков.
- summary: 3–5 коротких пунктов. questions: 3–5 вопросов для самопроверки, без ответов.
- Всё по-русски. Внутри строк JSON обратная косая черта LaTeX удваивается."""

    const val JSON_RETRY_SUFFIX = "Верни только валидный JSON."

    fun mentorSystem(subject: String, strictness: Strictness, coords: CoordMode = CoordMode.PIXELS_XY): String {
        val (c, rule, example) = when (coords) {
            CoordMode.PIXELS_XY -> Triple(COORDS_PIXELS, COORDS_PIXELS_RULE, EXAMPLE_PIXELS)
            CoordMode.NORM_XY -> Triple(COORDS_NORM_XY, COORDS_NORM_XY_RULE, EXAMPLE_NORM_XY)
            CoordMode.NORM_YX -> Triple(COORDS_NORM_YX, COORDS_NORM_YX_RULE, EXAMPLE_NORM_YX)
        }
        return MENTOR_TEMPLATE
            .replace("{SUBJECT}", subject.ifBlank { "не указан" })
            .replace("{STRICTNESS}", strictness.promptText)
            .replace("{COORDS_RULE}", rule)
            .replace("{COORDS}", c)
            .replace("{EXAMPLE}", example)
    }

    /** Текст последнего вопроса: к нему добавляется размер снимка, чтобы координаты были в его пикселях. */
    fun withShotSize(question: String, width: Int, height: Int): String =
        "$question\n\n[Снимок экрана: $width×$height пикселей]"

    fun cleanSystem(subject: String): String =
        CLEAN_TEMPLATE.replace("{SUBJECT}", subject.ifBlank { "не указан" })

    fun cleanUserText(shotCount: Int, retry: Boolean): String {
        val base = if (shotCount == 1) {
            "Вот снимок экрана моих заметок. Оформи чистовик."
        } else {
            "Вот $shotCount снимков экрана моих заметок, по порядку. Оформи из них один чистовик."
        }
        return if (retry) "$base\n\n$JSON_RETRY_SUFFIX" else base
    }

    fun isQuickPrompt(text: String): Boolean = QuickAction.entries.any { it.prompt == text } || text == WATCH_PROMPT

    /** Текст, которым в истории заменяется картинка из прошлых сообщений. */
    const val PAST_IMAGE_NOTE = "[к этому сообщению был приложен снимок экрана]"
}
